local family = (core.settings:get("mycraft_theme") or "teal"):lower()
local c = C[family] or C.teal

local function art(name)
	return core.get_texturepath_share() .. DIR_DELIM .. "base" ..
		DIR_DELIM .. "pack" .. DIR_DELIM .. name
end

mycraft_theme.colour = c
mycraft_theme.family = family

--- Returns a formspec fragment that restyles every widget type.
function mycraft_theme.style()
	local panel = core.formspec_escape(art("mycraft_ui_panel.png"))
	local btn = core.formspec_escape(art("mycraft_ui_btn.png"))
	local btn_h = core.formspec_escape(art("mycraft_ui_btn_hover.png"))
	local btn_p = core.formspec_escape(art("mycraft_ui_btn_press.png"))
	local tab_on = core.formspec_escape(art("mycraft_ui_tab_active.png"))
	local tab_off = core.formspec_escape(art("mycraft_ui_tab_idle.png"))

	local parts = {
		-- text everywhere
		"style_type[label;textcolor=" .. c.text .. "]",
		"style_type[button;textcolor=" .. c.text .. ";bgimg=" .. btn ..
			";bgimg_middle=14;border=false;padding=6]",
		"style_type[button:hovered;bgimg=" .. btn_h .. ";bgimg_middle=14]",
		"style_type[button:pressed;bgimg=" .. btn_p .. ";bgimg_middle=14]",
		"style_type[image_button;bgcolor=" .. c.tab_off .. ";border=false]",
		"style_type[tabheader;bgcolor=" .. tab_off .. ";textcolor=" .. c.soft ..
			";bgimg=" .. tab_off .. ";bgimg_middle=8;border=false]",
		"style_type[tabheader:hovered;bgimg=" .. tab_on .. ";bgimg_middle=8;textcolor=" .. c.text .. "]",
		"style_type[tabheader:selected;bgimg=" .. tab_on .. ";bgimg_middle=8;textcolor=" .. c.warm .. "]",
		"style_type[box;colors=" .. c.panel .. "]",
		"style_type[field;bgcolor=" .. c.field .. ";border=true;bordercolor=" .. c.edge ..
			";textcolor=" .. c.text .. "]",
		"style_type[textarea;bgcolor=" .. c.field .. ";border=true;bordercolor=" .. c.edge ..
			";textcolor=" .. c.text .. "]",
		"style_type[pwdfield;bgcolor=" .. c.field .. ";border=true;bordercolor=" .. c.edge ..
			";textcolor=" .. c.text .. "]",
		"style_type[dropdown;bgcolor=" .. c.field .. ";border=true;bordercolor=" .. c.edge ..
			";textcolor=" .. c.text .. "]",
		"style_type[table;background=" .. c.field .. ";color=" .. c.text ..
			";highlight=" .. c.tab_on .. "]",
		"style_type[textlist;background=" .. c.field .. ";color=" .. c.text ..
			";highlight=" .. c.tab_on .. "]",
		"style_type[item_image_button;bgcolor=" .. c.tab_off .. ";border=false]",
		"style_type[checkbox;textcolor=" .. c.text .. "]",
	}
	return table.concat(parts)
end

--- Call once at start-up: painted background + window title font colour.
function mycraft_theme.apply_background()
	core.set_background("background", art("mycraft_bg.png"))
	-- wordmark in the header layer (drawn by the engine, no layout impact)
	core.set_background("header", art("mycraft_logo.png"))
	core.set_background("footer", "")
	core.set_background("overlay", "")
	core.set_clouds(false)
end

--- Replaces the drag-and-drop dirt background of the engine.
function mycraft_theme.install()
	if mycraft_theme.installed then
		return
	end
	mycraft_theme.installed = true

	-- The engine's theme module switches to dirt/clouds for games without
	-- their own menu art. Keep our vista instead.
	if mm_game_theme then
		local old_reset = mm_game_theme.reset
		mm_game_theme.reset = function()
			old_reset()
			mycraft_theme.apply_background()
		end
		local old_dirt = mm_game_theme.set_dirt_bg
		mm_game_theme.set_dirt_bg = function()
			mycraft_theme.apply_background()
		end
		mm_game_theme.set_generic = function(identifier)
			-- header/footer/overlay art is not part of this theme
			if identifier == "background" then
				core.set_background("background", art("mycraft_bg.png"))
				return true
			end
			return false
		end
	end
end
