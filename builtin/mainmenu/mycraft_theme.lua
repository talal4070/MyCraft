Copyright (C) 2026 MyCraft contributors, LGPL-3.0-or-later

Applies one consistent, original look to every main-menu screen: a dusk
vista behind the menu, rounded slate panels, amber accents. It is a theme
layer only - buttons, tabs and dialogs stay where the engine puts them,
so nothing behaves differently, it just looks like MyCraft.

Art lives in textures/base/pack/mycraft_*.png and is generated by
tools/gen_icons.py in the MyCraft repository.

Colour family is picked with the "mycraft_theme" setting:
    teal   (default)  deep teal + amber
    violet            midnight violet + lime
    coral             slate + coral
    moss              forest moss + cream
]]

